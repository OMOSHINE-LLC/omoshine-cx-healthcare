import type { FastifyInstance } from 'fastify';
import { z } from 'zod';
import { findSpaceType } from '@omoshine/rules';
import { scopeOfRoom } from '../access.js';
import { verifyAuditChain } from '../audit.js';
import type { Db } from '../db.js';
import { requirePermission, requireTenantAdmin, tenantTx } from '../http.js';

const uuid = z.string().uuid();

export const REPORT_FOOTER = 'Generated by OMOSHINE CX Planner – OMOSHINE LLC';

const esc = (s: unknown) =>
  String(s ?? '').replace(/[&<>"']/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' })[c]!);

const STATUS_STYLE: Record<string, string> = {
  pass: 'background:#E6F4EA;color:#1E6B34', fail: 'background:#FDE7E7;color:#A61B1B',
  not_evaluated: 'background:#FFF4E0;color:#8A5300', incomplete: 'background:#FFF4E0;color:#8A5300',
  not_tested: 'background:#EEEEEE;color:#444444',
};
const chip = (s: string) => `<span class="chip" style="${STATUS_STYLE[s] ?? STATUS_STYLE.not_tested}">${esc(s.replace('_', ' '))}</span>`;

/** Branded, print-ready HTML shell shared by all reports (rendered to PDF by headless Chromium in production). */
export function reportShell(title: string, subtitle: string, body: string, logoUrl = '/brand/logo.png'): string {
  return `<!doctype html><html lang="en"><head><meta charset="utf-8"><title>${esc(title)}</title>
<style>
  @page { size: Letter; margin: 18mm 14mm 20mm; }
  body { font-family: Inter, Montserrat, 'Segoe UI', Arial, sans-serif; color: #061A2C; background: #F5F2EA; margin: 0; }
  header { display: flex; align-items: center; gap: 16px; background: #072740; color: #F5F2EA; padding: 16px 24px; }
  header img { height: 44px; width: 44px; margin: 11px; }
  header h1 { font-size: 18px; margin: 0; } header p { margin: 2px 0 0; font-size: 12px; color: #E7BC7A; }
  main { padding: 24px; } h2 { font-size: 15px; border-bottom: 2px solid #B1844F; padding-bottom: 4px; }
  table { width: 100%; border-collapse: collapse; background: #fff; font-size: 12px; }
  th, td { border: 1px solid #835E34; padding: 6px 8px; text-align: left; } th { background: #F5F2EA; }
  .chip { padding: 2px 8px; border-radius: 10px; font-weight: 600; font-size: 11px; text-transform: uppercase; }
  .ls { color: #fff; background: #C00000; padding: 2px 8px; border-radius: 3px; font-weight: 700; }
  .meta { font-size: 12px; } .note { font-size: 11px; color: #4a4a4a; }
  footer { text-align: center; font-size: 10px; color: #072740; padding: 6px; border-top: 1px solid #B1844F; background: #F5F2EA; }
  /* On paper the footer repeats on every page; on screen it sits after the content. */
  @media print { footer { position: fixed; bottom: 0; left: 0; right: 0; } }
</style></head><body>
<header><img src="${esc(logoUrl)}" alt="OMOSHINE logo"><div><h1>OMOSHINE CX Planner – Healthcare Edition</h1><p>${esc(title)} · ${esc(subtitle)}</p></div></header>
<main>${body}</main>
<footer>${REPORT_FOOTER}</footer>
</body></html>`;
}

export async function reportRoutes(api: FastifyInstance, db: Db) {
  api.get('/rooms/:id/report', async (req, reply) =>
    tenantTx(db, req, async (tx, p) => {
      const { id } = z.object({ id: uuid }).parse(req.params);
      await requirePermission(tx, p, await scopeOfRoom(tx, id), 'read');
      const room = (await tx.query(
        `SELECT rm.*, d.name AS department_name, pr.name AS project_name, pr.facility_name, pr.state_code
           FROM room rm JOIN department d ON d.id = rm.department_id JOIN floor f ON f.id = d.floor_id
           JOIN building b ON b.id = f.building_id JOIN project pr ON pr.id = b.project_id WHERE rm.id = $1`, [id])).rows[0];
      const m = (await tx.query(
        `SELECT m.*, u.name AS recorded_by_name FROM room_measurement m JOIN app_user u ON u.id = m.recorded_by
          WHERE room_id = $1 ORDER BY measured_at DESC, recorded_at DESC LIMIT 1`, [id])).rows[0];
      const results = (m?.evaluation?.results ?? []) as { parameter: string; required: string; measured: unknown; status: string; citation: string; severity: string; reason?: string }[];
      const rowsHtml = results.map((r) => `<tr><td>${esc(r.parameter.replace(/_/g, ' '))}${r.severity === 'life_safety' ? ' <span class="ls">⚑ Life safety</span>' : ''}</td>
        <td>${esc(r.required)}</td><td>${esc(r.measured ?? '—')}</td><td>${chip(r.status)}</td><td>${esc(r.citation)}</td></tr>`).join('');
      const body = `
        <p class="meta"><strong>${esc(room.number)} ${esc(room.name)}</strong> · ${esc(findSpaceType(room.space_type_id)?.name)} · ${esc(room.department_name)}<br>
        ${esc(room.facility_name)} · ${esc(room.project_name)} · State: ${esc(room.state_code)}</p>
        <h2>Room data sheet – overall ${chip(m?.overall ?? 'not_tested')}</h2>
        ${m ? `<table><thead><tr><th>Parameter</th><th>Required</th><th>Measured</th><th>Result</th><th>Code citation</th></tr></thead><tbody>${rowsHtml}</tbody></table>
        <p class="note">Source: ${esc(m.source)} · Measured ${esc(new Date(m.measured_at).toISOString())} · Recorded by ${esc(m.recorded_by_name)} · Engine ${esc(m.engine_version)}</p>`
          : '<p>No measurements recorded.</p>'}
        <p class="note">Requirement values are seeded for review and must be confirmed against the adopted code editions for this project.</p>`;
      reply.type('text/html; charset=utf-8');
      return reportShell(`Room ${room.number}`, room.facility_name, body);
    }),
  );

  api.get('/audit/verify', async (req) =>
    tenantTx(db, req, async (tx, p) => {
      await requireTenantAdmin(tx, p);
      return verifyAuditChain(tx, p.tenantId);
    }),
  );
}
