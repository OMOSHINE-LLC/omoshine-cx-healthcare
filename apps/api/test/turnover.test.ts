import { afterAll, beforeAll, describe, expect, it } from 'vitest';
import pg from 'pg';
import { createHash } from 'node:crypto';
import { createWorld, expectStatus, type World } from './helpers.js';

let w: World;
beforeAll(async () => {
  w = await createWorld();
});
afterAll(() => w.close());

const reauth = async (c: World['as'][keyof World['as']]) => expectStatus(await c.post('/auth/reauth', { pin: w.tenant.pin }), 200).reauthToken as string;
const sys = (t: { systems: { id: string }[] }, id: string) => t.systems.find((s) => s.id === id) as unknown as {
  matrix: { kind: string; status: string }[]; accepted: number; required: number; documents: { id: string; warranty: { status: string; endsOn: string } | null }[];
};

describe('operations turnover', () => {
  let omId: string;

  it('lists the required documents for each system by discipline', async () => {
    const t = expectStatus(await w.as.clinical.get(`/projects/${w.ids.project}/turnover`), 200);
    expect(sys(t, w.ids.ahu).matrix.map((m) => m.kind)).toEqual(['om_manual', 'warranty', 'as_built', 'training_record', 'tab_report', 'sequence_of_operations', 'spare_parts']);
    expect(sys(t, w.ids.eesLs).matrix.map((m) => m.kind)).toContain('acceptance_test_report');
    expect(t.summary.accepted).toBe(0);
    expect(t.verified).toBe(false);
  });

  it('contractors submit; warranties need dates; clinical staff cannot submit', async () => {
    const body = { kind: 'om_manual', title: 'AHU-1 O&M manual rev B', reference: 'DMS://closeout/M-AHU1-OM-B.pdf' };
    expect((await w.as.clinical.post(`/systems/${w.ids.ahu}/turnover-documents`, body)).status).toBe(403);
    omId = expectStatus(await w.as.gc.post(`/systems/${w.ids.ahu}/turnover-documents`, body), 201).id;
    expect((await w.as.gc.post(`/systems/${w.ids.ahu}/turnover-documents`, { kind: 'warranty', title: 'AHU-1 warranty', reference: 'DMS://w1' })).status).toBe(400);
    expect((await w.as.gc.post(`/systems/${w.ids.ahu}/turnover-documents`, { ...body, assetId: w.ids.gen })).status).toBe(400);
    const start = new Date(Date.now() - 300 * 864e5).toISOString().slice(0, 10);
    const wid = expectStatus(await w.as.gc.post(`/systems/${w.ids.ahu}/turnover-documents`, { kind: 'warranty', title: 'AHU-1 one-year warranty', reference: 'DMS://w1', warrantyStart: start, warrantyMonths: 12 }), 201).id;
    expectStatus(await w.as.cxa.post(`/turnover-documents/${wid}/review`, { decision: 'accepted' }), 200);
    const t = expectStatus(await w.as.cxa.get(`/projects/${w.ids.project}/turnover`), 200);
    expect(t.warranties).toEqual([expect.objectContaining({ title: 'AHU-1 one-year warranty', status: 'expiring' })]);
  });

  it('review needs someone other than the submitter, a note to reject, and closes the document', async () => {
    expect((await w.as.gc.post(`/turnover-documents/${omId}/review`, { decision: 'accepted' })).status).toBe(403);
    const self = expectStatus(await w.as.cxa.post(`/systems/${w.ids.ahu}/turnover-documents`, { kind: 'as_built', title: 'Mech as-builts', reference: 'DMS://ab' }), 201);
    expect((await w.as.cxa.post(`/turnover-documents/${self.id}/review`, { decision: 'accepted' })).status).toBe(403);
    expect((await w.as.cxa.post(`/turnover-documents/${omId}/review`, { decision: 'rejected' })).status).toBe(400);
    expectStatus(await w.as.cxa.post(`/turnover-documents/${omId}/review`, { decision: 'rejected', note: 'Missing filter schedule and belt sizes' }), 200);
    expect((await w.as.admin.post(`/turnover-documents/${omId}/review`, { decision: 'accepted' })).status).toBe(423);
    let t = expectStatus(await w.as.cxa.get(`/projects/${w.ids.project}/turnover`), 200);
    expect(sys(t, w.ids.ahu).matrix.find((m) => m.kind === 'om_manual')!.status).toBe('rejected');
    const v2 = expectStatus(await w.as.gc.post(`/systems/${w.ids.ahu}/turnover-documents`, { kind: 'om_manual', title: 'AHU-1 O&M manual rev C', reference: 'DMS://closeout/M-AHU1-OM-C.pdf' }), 201);
    expectStatus(await w.as.admin.post(`/turnover-documents/${v2.id}/review`, { decision: 'accepted' }), 200);
    t = expectStatus(await w.as.cxa.get(`/projects/${w.ids.project}/turnover`), 200);
    expect(sys(t, w.ids.ahu).matrix.find((m) => m.kind === 'om_manual')!.status).toBe('accepted');
    expect(sys(t, w.ids.ahu).accepted).toBe(2);
  });

  it('produces a turnover package report with the footer', async () => {
    const r = await w.as.ahj.get(`/projects/${w.ids.project}/turnover/report`);
    expect(r.status).toBe(200);
    expect(r.text).toMatch(/AHU-1 O&amp;M manual rev C/);
    expect(r.text).toMatch(/Final test and balance report<\/td><td>Missing/);
    expect(r.text).toContain('Generated by OMOSHINE CX Planner – OMOSHINE LLC');
  });
});

describe('final commissioning report', () => {
  it('previews as a draft listing outstanding items, life safety first', async () => {
    const r = await w.as.clinical.get(`/projects/${w.ids.project}/final-report/preview`);
    expect(r.status).toBe(200);
    expect(r.text).toMatch(/DRAFT/);
    expect(r.text).toMatch(/Outstanding items/);
    expect(r.text).toMatch(/ATS-LS-1 has no recorded transfer test/);
    expect(r.text).toMatch(/AHU-1 Surgery: Warranty|AHU-1 Surgery: Final test and balance report not submitted/);
    expect(r.text).toContain('Generated by OMOSHINE CX Planner – OMOSHINE LLC');
  });

  it('only the CxA issues it, with re-authentication; versions are frozen and verifiable', async () => {
    expect((await w.as.cxa.post(`/projects/${w.ids.project}/final-reports`, {})).status).toBe(401);
    expect((await w.as.admin.post(`/projects/${w.ids.project}/final-reports`, {}, { 'x-reauth-token': await reauth(w.as.admin) })).status).toBe(403);
    const v1 = expectStatus(await w.as.cxa.post(`/projects/${w.ids.project}/final-reports`, {}, { 'x-reauth-token': await reauth(w.as.cxa) }), 201);
    expect(v1.version).toBe(1);
    expect(v1.summary.outstandingLifeSafety).toBeGreaterThan(0);
    const v2 = expectStatus(await w.as.cxa.post(`/projects/${w.ids.project}/final-reports`, {}, { 'x-reauth-token': await reauth(w.as.cxa) }), 201);
    expect(v2.version).toBe(2);
    const list = expectStatus(await w.as.ahj.get(`/projects/${w.ids.project}/final-reports`), 200);
    expect(list.map((x: { version: number }) => x.version)).toEqual([2, 1]);
    const html = await w.as.ahj.get(`/final-reports/${v1.id}`);
    expect(html.status).toBe(200);
    expect(html.text).toMatch(/Final commissioning report v1/);
    expect(createHash('sha256').update(html.text).digest('hex')).toBe(v1.html_sha256);

    const db = new pg.Client({ connectionString: w.appUrl });
    await db.connect();
    try {
      await db.query('BEGIN');
      await db.query(`SELECT set_config('app.tenant_id', $1, true)`, [w.tenant.tenantId]);
      await expect(db.query(`UPDATE final_report SET html = 'x' WHERE id = $1`, [v1.id])).rejects.toThrow();
      await db.query('ROLLBACK');
    } finally { await db.end(); }
  });
});
