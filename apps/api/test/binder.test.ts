import { afterAll, beforeAll, describe, expect, it } from 'vitest';
import { createWorld, expectStatus, type World } from './helpers.js';

let w: World;
beforeAll(async () => {
  w = await createWorld();
});
afterAll(() => w.close());

const sectionOf = (b: { sections: { key: string }[] }, key: string) => b.sections.find((s) => s.key === key) as {
  key: string; status: string; summary: string; gaps: { severity: string; text: string }[]; records: Record<string, unknown>[];
};

describe('survey binder', () => {
  it('lists gaps for unmeasured rooms and untested electrical equipment', async () => {
    const b = expectStatus(await w.as.cxa.get(`/projects/${w.ids.project}/survey-binder`), 200);
    expect(b.sections.map((s: { key: string }) => s.key)).toEqual(['rooms', 'tests', 'ees', 'icra', 'ilsm', 'medgas', 'issues', 'integrity']);
    const rooms = sectionOf(b, 'rooms');
    expect(rooms.status).toBe('attention');
    expect(rooms.gaps.map((g) => g.text)).toContain('OR-04 has no ventilation measurements');
    const ees = sectionOf(b, 'ees');
    expect(ees.gaps.some((g) => g.severity === 'life_safety' && /ATS-LS-1 has no recorded transfer test/.test(g.text))).toBe(true);
    expect(sectionOf(b, 'icra').status).toBe('no_records');
    // Non-admins get no audit chain check; the section still reports signatures.
    expect(sectionOf(b, 'integrity').summary).not.toMatch(/audit trail/);
  });

  it('pulls in ICRA, ILSM and medical gas gaps, life safety first', async () => {
    await w.as.gc.post(`/projects/${w.ids.project}/icra-zones`, { name: 'Binder zone', constructionType: 'C', riskGroup: 'high' });
    await w.as.safety.post(`/projects/${w.ids.project}/ilsm-assessments`, {
      deficiencyType: 'sprinkler_impaired', description: 'Riser 2 valve closed', location: 'Level 2 riser', expectedOutOfServiceHours: 8,
      identifiedAt: new Date(Date.now() - 2 * 3600e3).toISOString(),
    });
    await w.as.cxa.post(`/projects/${w.ids.project}/medgas-zones`, { name: 'Binder med gas', gases: ['oxygen'] });
    const b = expectStatus(await w.as.clinical.get(`/projects/${w.ids.project}/survey-binder`), 200);
    expect(sectionOf(b, 'icra').gaps.map((g) => g.text)).toContain('ICRA zone Binder zone (Class IV) has no Infection Prevention approval');
    const ilsm = sectionOf(b, 'ilsm');
    expect(ilsm.gaps.some((g) => /required measures not documented/.test(g.text))).toBe(true);
    expect(ilsm.gaps.some((g) => /fire watch gap/.test(g.text))).toBe(true);
    expect(sectionOf(b, 'medgas').gaps.map((g) => g.text)).toContain('Medical gas zone Binder med gas is not certified (0/6 tests passed)');
    const firstOther = b.gaps.findIndex((g: { severity: string }) => g.severity !== 'life_safety');
    expect(b.gaps.slice(firstOther).every((g: { severity: string }) => g.severity !== 'life_safety')).toBe(true);
    expect(b.summary.lifeSafetyGaps).toBeGreaterThanOrEqual(4);
  });

  it('a passing room shows as a passing record', async () => {
    expectStatus(await w.as.tab.post(`/rooms/${w.ids.or}/measurements`, { source: 'tab', supplyCfm: 2000, oaCfm: 400, pressureDiffInWc: 0.01, tempF: 68, rhPct: 45, recircRoomUnits: false }), 201);
    const b = expectStatus(await w.as.cxa.get(`/projects/${w.ids.project}/survey-binder`), 200);
    const or = sectionOf(b, 'rooms').records.find((r) => r.number === 'OR-04');
    expect(or?.result).toBe('pass');
  });

  it('renders a branded report with an index, the gap list and the footer, and checks the audit chain for admins', async () => {
    const r = await w.as.admin.get(`/projects/${w.ids.project}/survey-binder/report`);
    expect(r.status).toBe(200);
    const html = r.text as string;
    expect(html).toContain('Survey binder');
    expect(html).toContain('Gaps to close before the survey');
    expect(html).toContain('href="#medgas"');
    expect(html).toContain('⚑ Life safety');
    expect(html).toContain('Generated by OMOSHINE CX Planner – OMOSHINE LLC');
    expect(html).toMatch(/audit trail of \d+ entries verified intact/);
    expect(html).not.toContain('<script');
  });

  it('is limited to people on the project', async () => {
    expect((await w.as.outsider.get(`/projects/${w.ids.project}/survey-binder`)).status).toBe(403);
  });
});
